#!/usr/bin/env python3
"""Write assets/ART_MANIFEST.json and assets/ART_MANIFEST.md from objects.py,
and save the current placeholder for every sprite to assets/art_reference/
(handy as a layout guide when painting the real art).

    python3 tools/write_manifest.py
"""
import json
import os
import sys

os.environ.setdefault("SDL_VIDEODRIVER", "dummy")
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..")
sys.path.insert(0, ROOT)

import pygame  # noqa: E402

import art  # noqa: E402
import mansion  # noqa: E402
from objects import T, TILE_W, TILE_H, WALL_H, CHAR_H, WALL_ART_W, footprint  # noqa: E402

KIND_NOTES = {
    "furniture": "Isometric 3/4 view from above (2:1 dimetric), front facing the viewer's lower RIGHT, back against the upper-left wall. "
                 "Footprint diamond touches the bottom of the canvas. The game mirrors it for objects against the other wall.",
    "flat": "Lies flat on the floor, same isometric view; footprint diamond fills the canvas width.",
    "link": "Isometric, like furniture: front facing the lower right, back against the upper-left wall.",
    "wall": "FLAT FRONT VIEW (not isometric), as if photographed straight on. The game squeezes and shears it onto the wall.",
    "enemy": "Full figure, 3/4 view facing the viewer's lower RIGHT, feet (or lowest point) at the bottom of the canvas. "
             "The game mirrors it when the enemy moves left.",
    "item": "Small item, 3/4 view, centred.",
}


def uses():
    h = mansion.Mansion()
    count = {}
    rooms = {}
    for r in h.rooms.values():
        for o in r.objs + r.walls:
            count[o.type] = count.get(o.type, 0) + 1
            rooms.setdefault(o.type, set()).add(r.name)
        for e in r.enemies:
            count[e] = count.get(e, 0) + 1
            rooms.setdefault(e, set()).add(r.name)
    return count, rooms


def main():
    pygame.init()
    pygame.display.set_mode((16, 16))
    count, rooms = uses()
    ref_dir = os.path.join(ROOT, "assets", "art_reference")
    os.makedirs(ref_dir, exist_ok=True)
    sprites = []
    for name, t in T.items():
        tw, th = art.target_size(name)
        entry = {
            "name": name,
            "file": f"assets/art/{name}.png",
            "kind": t["kind"],
            "description": t["desc"],
            "target_px": [tw, th],
            "paint_at_px": [tw * 2, th * 2],
            "view": KIND_NOTES[t["kind"]],
            "used": count.get(name, 0),
            "rooms": sorted(rooms.get(name, [])),
            "placeholder": f"assets/art_reference/{name}.png",
        }
        if t["kind"] in ("furniture", "flat", "link"):
            gx, gy = footprint(name, "E")
            entry["footprint_tiles"] = {"width_along_front": t["size"][0], "depth": t["size"][1],
                                        "grid_when_facing_east": [gx, gy]}
            entry["object_height_px"] = t["h"]
            entry["footprint_bottom_vertex_x_px"] = gx * TILE_W // 2
        if t["kind"] == "wall":
            entry["span_tiles"] = t["size"][0]
        flags = [f for f in ("solid", "push", "lift") if t.get(f)]
        if t.get("search"):
            flags.append(f"search:{t['search']}")
        if t.get("glow"):
            flags.append("glows")
        entry["gameplay"] = flags
        sprites.append(entry)
        pygame.image.save(art.make_placeholder(name), os.path.join(ref_dir, name + ".png"))
    chars = [{"name": f"{c}_{k}", "file": f"assets/characters/{c}_{k}.png", "status": "done (tools/make_sprites.py)"}
             for c in ("archie", "holly") for k in ("se", "sw", "ne", "nw")]
    data = {
        "game": "Haunted Mansion (working title)",
        "resolution": [1280, 800],
        "tile_px": [TILE_W, TILE_H],
        "wall_height_px": WALL_H,
        "character_height_px": CHAR_H,
        "wall_art_px_per_tile": WALL_ART_W,
        "style": "Painted, soft-shaded cartoon Halloween style matching Archie and Holly; rich but slightly muted colours, "
                 "warm candlelight and cool moonlight; light from the upper left; transparent background (PNG with alpha), "
                 "no drop shadow on the floor (the game adds one), no text.",
        "how_to_add": "Save a transparent PNG as assets/art/<name>.png. Any size: it is cropped to its opaque area and scaled "
                      "(furniture to the footprint width, enemies to the target height, wall art to the exact target box). "
                      "Run the game; real art replaces the placeholder automatically.",
        "sprites": sprites,
        "characters": chars,
    }
    with open(os.path.join(ROOT, "assets", "ART_MANIFEST.json"), "w") as f:
        json.dump(data, f, indent=1)
    md = ["# Haunted Mansion: art manifest", "",
          "Generated by `tools/write_manifest.py` from `objects.py`, so sizes always match the game. "
          "Each sprite currently has a procedural placeholder (see `assets/art_reference/<name>.png` for its layout).", "",
          f"- Screen: 1280 x 800, drawn natively (no scaling).",
          f"- Floor tile: {TILE_W} x {TILE_H} px (2:1 isometric). Back walls {WALL_H} px tall. Archie and Holly are {CHAR_H} px tall.",
          f"- Style: {data['style']}",
          f"- Adding art: {data['how_to_add']}",
          "- Paint at roughly twice the target size (column *Paint at*); the game downsizes it with smooth scaling.", "",
          "## Views", ""]
    for k, v in KIND_NOTES.items():
        md.append(f"- **{k}**: {v}")
    sections = [("Furniture: hiding places (searchable)", lambda t: t["kind"] == "furniture" and t.get("search")),
                ("Furniture: pushable (key can be underneath)", lambda t: t["kind"] == "furniture" and t.get("push")),
                ("Furniture: scenery", lambda t: t["kind"] == "furniture" and not t.get("search") and not t.get("push")),
                ("Floor objects", lambda t: t["kind"] == "flat"),
                ("Stairs, ladders and trapdoors", lambda t: t["kind"] == "link"),
                ("Wall hangings (flat front view)", lambda t: t["kind"] == "wall"),
                ("Ghosts, goblins and monsters", lambda t: t["kind"] == "enemy"),
                ("Items", lambda t: t["kind"] == "item")]
    for title, pred in sections:
        md += ["", f"## {title}", "",
               "| Name (file `assets/art/<name>.png`) | Footprint (front x depth tiles) | Target px (w x h) | Paint at | Used | Description |",
               "|---|---|---|---|---|---|"]
        for e in sprites:
            t = T[e["name"]]
            if not pred(t):
                continue
            fp = e.get("footprint_tiles")
            fps = f"{fp['width_along_front']} x {fp['depth']}" if fp else (f"{e['span_tiles']} tile wide" if "span_tiles" in e else "-")
            md.append(f"| `{e['name']}` | {fps} | {e['target_px'][0]} x {e['target_px'][1]} | "
                      f"{e['paint_at_px'][0]} x {e['paint_at_px'][1]} | {e['used']} | {e['description']} |")
    md += ["", "## Characters (done)", "",
           "Archie and Holly, four facings each, in `assets/characters/`, built by `tools/make_sprites.py` from the "
           "high-resolution sources in `tools/art/` (160 px figures on a 168 px canvas).", ""]
    with open(os.path.join(ROOT, "assets", "ART_MANIFEST.md"), "w") as f:
        f.write("\n".join(md) + "\n")
    print(f"{len(sprites)} sprites -> assets/ART_MANIFEST.json, assets/ART_MANIFEST.md, assets/art_reference/")


if __name__ == "__main__":
    main()
